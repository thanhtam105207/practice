create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'ENT303 Learner',
  class_code text not null default 'ENT303-2026',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.study_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null,
  xp integer not null check (xp between 0 and 100),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.study_events enable row level security;

drop policy if exists "profiles_select_authenticated" on public.profiles;
create policy "profiles_select_authenticated" on public.profiles for select to authenticated using (true);

drop policy if exists "profiles_insert_self" on public.profiles;
create policy "profiles_insert_self" on public.profiles for insert to authenticated with check (auth.uid() = id);

drop policy if exists "profiles_update_self" on public.profiles;
create policy "profiles_update_self" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "events_insert_self" on public.study_events;
create policy "events_insert_self" on public.study_events for insert to authenticated with check (auth.uid() = user_id);

create or replace function public.record_study_event(p_kind text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  pts integer;
  today_count integer;
  today_xp integer;
begin
  if uid is null then raise exception 'not_authenticated'; end if;
  pts := case p_kind
    when 'vocab_learned' then 2
    when 'vocab_correct' then 2
    when 'grammar_correct' then 3
    when 'quiz_complete_80' then 25
    when 'quiz_complete_100' then 50
    when 'lesson_complete' then 20
    else 0 end;
  if pts <= 0 then raise exception 'invalid_event'; end if;
  select coalesce(sum(xp),0), count(*) into today_xp,today_count
  from public.study_events
  where user_id=uid
    and created_at >= (date_trunc('day', now() at time zone 'Asia/Ho_Chi_Minh') at time zone 'Asia/Ho_Chi_Minh');
  if today_xp >= 300 then return json_build_object('ok',false,'xp',0,'reason','daily_cap'); end if;
  pts := least(pts, 300-today_xp);
  insert into public.study_events(user_id,kind,xp) values(uid,p_kind,pts);
  return json_build_object('ok',true,'xp',pts);
end; $$;

grant execute on function public.record_study_event(text) to authenticated;

create or replace function public.get_weekly_leaderboard(p_class_code text default 'ENT303-2026')
returns table(user_id uuid, display_name text, class_code text, weekly_xp bigint)
language sql
security definer
set search_path = public
as $$
  select p.id, p.display_name, p.class_code, coalesce(sum(e.xp),0)::bigint as weekly_xp
  from public.profiles p
  left join public.study_events e on e.user_id=p.id
    and e.created_at >= (date_trunc('week', now() at time zone 'Asia/Ho_Chi_Minh') at time zone 'Asia/Ho_Chi_Minh')
  where p.class_code = p_class_code
  group by p.id,p.display_name,p.class_code
  order by weekly_xp desc, p.display_name asc;
$$;

grant execute on function public.get_weekly_leaderboard(text) to authenticated;

-- Optional: automatically create a profile row when a new auth user signs up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,display_name,class_code)
  values(new.id, coalesce(new.raw_user_meta_data->>'display_name',split_part(new.email,'@',1)), coalesce(new.raw_user_meta_data->>'class_code','ENT303-2026'))
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();


create or replace function public.get_previous_week_winner(p_class_code text default 'ENT303-2026')
returns table(display_name text, class_code text, weekly_xp bigint)
language sql
security definer
set search_path = public
as $$
  select p.display_name, p.class_code, coalesce(sum(e.xp),0)::bigint as weekly_xp
  from public.profiles p
  left join public.study_events e on e.user_id=p.id
    and e.created_at >= ((date_trunc('week', now() at time zone 'Asia/Ho_Chi_Minh') - interval '7 days') at time zone 'Asia/Ho_Chi_Minh')
    and e.created_at < (date_trunc('week', now() at time zone 'Asia/Ho_Chi_Minh') at time zone 'Asia/Ho_Chi_Minh')
  where p.class_code=p_class_code
  group by p.id,p.display_name,p.class_code
  order by weekly_xp desc, p.display_name asc
  limit 1;
$$;

grant execute on function public.get_previous_week_winner(text) to authenticated;
